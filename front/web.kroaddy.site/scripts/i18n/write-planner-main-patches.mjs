function buildFromJa(modes, userPartial, stdPartial) {
  const x = structuredClone(ja);
  Object.assign(x.modes.standard, modes.standard);
  Object.assign(x.modes.kcontent, modes.kcontent);
  Object.assign(x.modes.usercontent, modes.usercontent);
  Object.assign(x.usercontent, userPartial);
  Object.assign(x.standard, stdPartial);
  if (stdPartial.highlight) x.standard.highlight = stdPartial.highlight;
  if (stdPartial.theme) x.standard.theme = stdPartial.theme;
  return x;
}

